"""Settings reference and default parameter file, generated from the schema.

Both outputs are built from the settings table (`pdukit.config.schema`), so
they cannot drift from the code:

``python -m pdukit.config.reference --markdown``
    The reference page (``docs/OPTIONS.md``): every setting with its default,
    allowed values, meaning and the presets that change it.
``python -m pdukit.config.reference --ppf``
    A parameter file with every setting at its default
    (``pdukit/params/default.ppf``); copy it and edit what you need.
``--write``
    Rewrite both files in the repository.

A test fails when either file is out of date or a setting has no help text.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path

from pdukit.config import SETTINGS, guide
from pdukit.config.config import TRUE
from pdukit.io.ppf import read_ppf

PARAMS = Path(__file__).resolve().parents[1] / "params"
REPO = Path(__file__).resolve().parents[2]
PPF_HEADER = """\
; PDU default parameter file: every setting at its built-in default.
; Generated by `python -m pdukit.config.reference --write`; do not
; edit by hand.  Copy it, delete the lines you do not change and use it with
; `pdu run -p my.ppf ...`.  Precedence: command line, then this file, then
; the built-in default.  Settings that describe a run rather than the
; science (files, output folder, threads) are not listed.  The full text of
; each setting is in docs/OPTIONS.md.
"""


def options_without_help():
    """Return the keys of the settings that have no help text."""
    return [row[1] for row in SETTINGS if not row[8]]


def preset_values():
    """Return {preset name: {setting key: text}} for the shipped presets."""
    out = {}
    for path in sorted(PARAMS.glob("*.ppf")):
        if path.name == "default.ppf":
            continue
        out[path.stem] = {k: v for k, v, _ in read_ppf(path) if v != ""}
    return out


def _default_text(kind, default):
    if kind == "flag":
        return "off"
    if kind == "noflag":
        return "on"
    if default is None:
        return "unset"
    if isinstance(default, (list, tuple)):
        return " ".join(str(v) for v in default)
    return str(default)


def _format_value(kind, value):
    """Return a value as it is written in a parameter file."""
    if kind == "flag":
        return "1" if value else "0"
    if kind == "noflag":
        return "0" if value else "1"
    if isinstance(value, (list, tuple)):
        return " ".join(str(v) for v in value)
    return str(value)


def _same_as_default(kind, default, text):
    """Return whether a parameter-file value equals the setting's default."""
    word = text.strip().lower()
    if kind in ("flag", "noflag"):
        return (word in TRUE) == (default is True)
    shown = _default_text(kind, default)
    if word == shown.lower():
        return True
    try:
        return float(word) == float(shown)
    except ValueError:
        return False


def _clean(text):
    return re.sub(r"\s+", " ", text or "").replace("|", "\\|").strip()


def render_markdown():
    """Return the settings reference as markdown text."""
    presets = preset_values()
    rows = {row[1]: row for row in SETTINGS}
    lines = [
        "# PDU settings reference",
        "",
        "Generated from the settings table by "
        "`python -m pdukit.config.reference --write`; "
        "do not edit by hand (the explanations are in "
        "`pdukit/config/guide.py`).",
        "",
        guide.INTRO.rstrip(),
        "",
        "## Start here: the settings most runs change",
        "",
        "| setting | default | what it means |",
        "|---|---|---|",
    ]
    for key, text in guide.START_HERE:
        row = rows[key]
        lines.append(
            f"| `{key}` | {_clean(_default_text(row[3], row[4]))} "
            f"| {_clean(text)} |"
        )
    lines += [
        "",
        "## Memory, time and where to run",
        "",
        guide.RUN_SIZE.rstrip(),
        "",
        "## All settings",
        "",
        "The last column lists the shipped presets that change the option "
        "from its default, with their value.",
        "",
    ]
    title = None
    for (group, key, _, kind, default, choices, many, run_specific,
         help_) in SETTINGS:
        if group != title:
            title = group
            lines += [
                f"### {title[0].upper() + title[1:]}",
                "",
                guide.GROUP_INTRO[title],
                "",
                "| setting | default | values | what it does | presets |",
                "|---|---|---|---|---|",
            ]
        values = ", ".join(map(str, choices)) if choices else ""
        if many:
            values = "one or more"
        sets = ", ".join(
            f"{name}: {vals[key]}"
            for name, vals in presets.items()
            if key in vals and not _same_as_default(kind, default, vals[key])
        )
        run = " (run-specific, not in parameter files)" * run_specific
        lines.append(
            f"| `{key}` | {_clean(_default_text(kind, default))} | {values} "
            f"| {_clean(help_)}{run} | {_clean(sets)} |"
        )
    # a blank line closes each table
    out, prev = [], ""
    for line in lines:
        if line.startswith("#") and prev.startswith("|"):
            out.append("")
        out.append(line)
        prev = line
    out += ["", "## Shipped presets", "",
            "In `pdukit/params/` (installed with the package; "
            "`python -c \"from importlib.resources import files; "
            "print(files('pdukit.params'))\"` prints the folder).", ""]
    for name, first in preset_summaries():
        out.append(f"- `{name}.ppf`: {_clean(first)}")
    out.append("- `final/`: the final runs of the paper (T4L WT and L99A, "
               "Syt1 C2A, mdCATH) at seven lags, with `submit_final.sh`")
    return "\n".join(out) + "\n"


def preset_summaries():
    """Return (name, first comment sentence) for each shipped preset."""
    out = []
    for path in sorted(PARAMS.glob("*.ppf")):
        if path.name == "default.ppf":
            continue
        text = []
        for line in path.read_text().splitlines():
            if not line.startswith(";"):
                break
            text.append(line.lstrip("; ").strip())
        words = " ".join(t for t in text if t).split(". ")[0].rstrip(".")
        out.append((path.stem, words or "(no description)"))
    return out


def render_default_ppf():
    """Return a parameter file with every setting at its default."""
    lines = [PPF_HEADER.rstrip("\n")]
    title = None
    for (group, key, _, kind, default, choices, _, run_specific,
         help_) in SETTINGS:
        if group == "planted benchmark" or run_specific:
            continue
        if group != title:
            title = group
            lines += ["", f"; ---- {group} ----"]
        note = _clean(help_).replace("\\|", "|")
        if choices:
            note += f" [{', '.join(map(str, choices))}]"
        lines.append("")
        lines += ["; " + w for w in textwrap.wrap(note, width=74)]
        if default is None:
            lines.append(f";{key} =")
        else:
            lines.append(f"{key} = {_format_value(kind, default)}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    """Print or write the generated files."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--ppf", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    if a.write:
        (REPO / "docs").mkdir(exist_ok=True)
        (REPO / "docs" / "OPTIONS.md").write_text(render_markdown())
        (PARAMS / "default.ppf").write_text(render_default_ppf())
        print("wrote docs/OPTIONS.md and pdukit/params/default.ppf")
    elif a.ppf:
        sys.stdout.write(render_default_ppf())
    else:
        sys.stdout.write(render_markdown())
    return 0


if __name__ == "__main__":
    sys.exit(main())
